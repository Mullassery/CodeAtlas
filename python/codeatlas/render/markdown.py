"""Markdown + Mermaid rendering."""

from __future__ import annotations

from typing import Any

from codeatlas.render import sanitize


def mermaid(components: list[dict[str, Any]], relations: list[dict[str, Any]]) -> str:
    lines = ["```mermaid", "graph LR"]
    for component in components:
        key = sanitize(component["name"])
        lines.append(f'    {key}["{component["name"]}"]')
    for relation in relations:
        src = sanitize(relation["src_name"])
        dst = sanitize(relation["dst_name"])
        lines.append(f'    {src} -- "{relation["relation"]}" --> {dst}')
    for component in components:
        if component.get("can_expand"):
            key = sanitize(component["name"])
            lines.append(f'    click {key} href "./{key}.md" "Details"')
    lines.append("```")
    return "\n".join(lines)


def generate_markdown(doc: dict[str, Any]) -> str:
    components = doc.get("components", [])
    relations = doc.get("relations", [])
    description = doc.get("description", "")

    lines = [mermaid(components, relations), "", "_Generated by CodeAtlas._", ""]
    if description:
        lines += ["## Details", "", description, ""]

    for component in components:
        name = component.get("name", "")
        key = sanitize(name)
        lines.append(f"### {name}")
        lines.append("")
        lines.append(component.get("description", ""))
        lines.append("")

        key_entities = component.get("key_entities", [])
        if key_entities:
            lines.append("**Related Classes/Methods:**")
            lines.append("")
            for entity in key_entities:
                qname = entity.get("qualified_name", "")
                ref = entity.get("reference_file", "")
                if ref:
                    lines.append(f"- `{qname}` (`{ref}`)")
                else:
                    lines.append(f"- `{qname}`")
            lines.append("")
        else:
            lines.append("**Related Classes/Methods:** _None_")
            lines.append("")

        file_methods = component.get("file_methods", [])
        if file_methods:
            lines.append("**Source Files:**")
            lines.append("")
            for group in file_methods:
                lines.append(f"- `{group.get('file_path', '')}`")
                for method in group.get("methods", []):
                    lines.append(f"  - `{method}`")
            lines.append("")

    return "\n".join(lines).rstrip() + "\n"
